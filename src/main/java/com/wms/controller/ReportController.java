    // ========================================
    // VIEW OPERATIONS
    // ========================================
    
    /**
     * VIEW REPORT
     * -----------
     */
    @GetMapping("/{id}")
    public String viewReport(@PathVariable("id") Long id, Model model) {
        Report report = reportService.getReportById(id)
                .orElseThrow(() -> new RuntimeException("Report not found with ID: " + id));
        
        model.addAttribute("report", report);
        
        // Add generated by username if available
        if (report.getGeneratedBy() != null) {
            userService.getUserById(report.getGeneratedBy())
                .ifPresent(user -> model.addAttribute("generatedByUsername", user.getUsername()));
        }
        
        // Parse allocation summary into structured list for display
        // Format: "VTI (Total Stock Market): ₹21,800 (40%)"
        if (report.getPortfolio() != null && report.getPortfolio().getAllocationSummary() != null 
                && !report.getPortfolio().getAllocationSummary().trim().isEmpty()) {
            String allocationSummary = report.getPortfolio().getAllocationSummary();
            java.util.List<java.util.Map<String, String>> allocations = new java.util.ArrayList<>();
            String[] lines = allocationSummary.split("\\r?\\n");
            for (String line : lines) {
                if (line != null && line.contains(":") && line.contains("₹")) {
                    java.util.Map<String, String> item = new java.util.HashMap<>();
                    
                    // Asset name is before the colon
                    item.put("asset", line.substring(0, line.indexOf(":")).trim());
                    
                    // Get the part after the colon: " ₹21,800 (40%)"
                    String afterColon = line.substring(line.indexOf(":") + 1).trim();
                    
                    // Extract value - from ₹ to the last ( which indicates percentage
                    String value = "-";
                    String pct = "-";
                    int rupeeIdx = afterColon.indexOf("₹");
                    int lastParenIdx = afterColon.lastIndexOf("(");
                    
                    if (rupeeIdx >= 0 && lastParenIdx > rupeeIdx) {
                        value = afterColon.substring(rupeeIdx, lastParenIdx).trim();
                    }
                    
                    // Extract percentage - between last ( and )
                    int lastCloseParenIdx = afterColon.lastIndexOf(")");
                    if (lastParenIdx >= 0 && lastCloseParenIdx > lastParenIdx) {
                        pct = afterColon.substring(lastParenIdx + 1, lastCloseParenIdx);
                    }
                    
                    item.put("value", value);
                    item.put("percentage", pct);
                    
                    allocations.add(item);
                }
            }
            model.addAttribute("allocations", allocations);
            
            // Always pass raw allocation summary for fallback display
            model.addAttribute("rawAllocationSummary", allocationSummary);
        }
        
        return "report/view";
    }
    
    // ========================================
    // GENERATE OPERATIONS
    // ========================================
    
    /**
     * SHOW GENERATE FORM (via /new path)
     * ----------------------------------
     */
    @GetMapping("/new")
    public String showNewForm(
            @RequestParam(value = "portfolioId", required = false) Long portfolioId,
            Model model) {
        return showGenerateForm(portfolioId, model);
    }
    
    /**
     * SHOW GENERATE FORM
     * ------------------
     */
    @GetMapping("/generate")
    public String showGenerateForm(
            @RequestParam(value = "portfolioId", required = false) Long portfolioId,
            Model model) {
        
        Report report = new Report();
        
        if (portfolioId != null) {
            Portfolio portfolio = portfolioService.getPortfolioById(portfolioId).orElse(null);
            report.setPortfolio(portfolio);
            model.addAttribute("selectedPortfolioId", portfolioId);
        }
        
        model.addAttribute("report", report);
        model.addAttribute("portfolios", portfolioService.getAllPortfolios());
        model.addAttribute("reportTypes", ReportType.values());
        return "report/form";
    }
    
    /**
     * CREATE REPORT (POST to /reports)
     * ---------------------------------
     */
    @PostMapping
    public String createReport(
            @Valid @ModelAttribute("report") Report report,
            BindingResult bindingResult,
            @RequestParam("portfolioId") Long portfolioId,
            Authentication authentication,
            RedirectAttributes redirectAttributes,
            Model model) {
        return generateReport(report, bindingResult, portfolioId, authentication, redirectAttributes, model);
    }
    
    /**
     * GENERATE REPORT
     * ---------------
     */
    @PostMapping("/generate")
    public String generateReport(
            @Valid @ModelAttribute("report") Report report,
            BindingResult bindingResult,
            @RequestParam("portfolioId") Long portfolioId,
            Authentication authentication,
            RedirectAttributes redirectAttributes,
            Model model) {
        
        if (bindingResult.hasErrors()) {
            model.addAttribute("portfolios", portfolioService.getAllPortfolios());
            model.addAttribute("reportTypes", ReportType.values());
            return "report/form";
        }
        
        try {
            // Set the generatedBy field from authenticated user
            if (authentication != null) {
                userService.getUserByUsername(authentication.getName())
                    .ifPresent(user -> report.setGeneratedBy(user.getUserId()));
            }
            
            Report saved = reportService.generateReport(portfolioId, report);
            redirectAttributes.addFlashAttribute("success", "Report generated successfully!");
            return "redirect:/reports/" + saved.getReportId();
            
        } catch (Exception e) {
            redirectAttributes.addFlashAttribute("error", e.getMessage());
            return "redirect:/reports/generate?portfolioId=" + portfolioId;
        }
    }
    
