    /**
     * GET USER NAMES MAP
     * ------------------
     * Creates a map of user IDs to usernames for display in templates.
     */
    private java.util.Map<Long, String> getUserNamesMap(List<Report> reports) {
        java.util.Map<Long, String> userNames = new java.util.HashMap<>();
        for (Report report : reports) {
            if (report.getGeneratedBy() != null && !userNames.containsKey(report.getGeneratedBy())) {
                userService.getUserById(report.getGeneratedBy())
                    .ifPresent(user -> userNames.put(report.getGeneratedBy(), user.getFullName() != null ? user.getFullName() : user.getUsername()));
            }
        }
        return userNames;
    }
